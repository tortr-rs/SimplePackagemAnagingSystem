//! env-update: /etc/env.d -> /etc/profile.env, /etc/csh.env, /etc/ld.so.conf, ldconfig.

use crate::shellvars;
use crate::util::{info, sorted_config_files, warn};
use std::collections::{BTreeMap, HashMap};
use std::path::Path;

const COLON: &[&str] = &[
    "ADA_INCLUDE_PATH", "ADA_OBJECTS_PATH", "CLASSPATH", "INFODIR", "INFOPATH", "KDEDIRS", "LDPATH", "MANPATH",
    "PATH", "PKG_CONFIG_PATH", "PRELINK_PATH", "PRELINK_PATH_MASK", "PYTHONPATH", "ROOTPATH",
];
const SPACE: &[&str] = &["CONFIG_PROTECT", "CONFIG_PROTECT_MASK"];
const HEADER: &str = "# THIS FILE IS AUTOMATICALLY GENERATED BY env-update.\n# DO NOT EDIT THIS FILE. CHANGES TO STARTUP PROFILES\n# GO INTO /etc/profile NOT /etc/profile.env\n\n";

fn write_if_changed(p: &Path, text: &str) -> Result<bool, String> {
    if std::fs::read_to_string(p).ok().as_deref() == Some(text) {
        return Ok(false);
    }
    let tmp = p.with_extension("spas-new");
    std::fs::write(&tmp, text).map_err(|e| format!("{}: {e}", tmp.display()))?;
    std::fs::rename(&tmp, p).map_err(|e| format!("{}: {e}", p.display()))?;
    Ok(true)
}

pub fn env_update(root: &Path, run_ldconfig: bool) -> Result<(), String> {
    let envd = root.join("etc/env.d");
    if !envd.is_dir() {
        return Ok(());
    }
    let mut colon: Vec<String> = COLON.iter().map(|s| s.to_string()).collect();
    let mut space: Vec<String> = SPACE.iter().map(|s| s.to_string()).collect();
    let mut files = Vec::new();
    for f in sorted_config_files(&envd) {
        // only plain files directly in env.d
        if f.parent() != Some(envd.as_path()) {
            continue;
        }
        match shellvars::parse_file(&f, &HashMap::new()) {
            Ok(v) => files.push(v),
            Err(e) => warn(&format!("env-update: {e}")),
        }
    }
    for v in &files {
        for (k, val) in v {
            if k == "COLON_SEPARATED" {
                colon.extend(val.split_whitespace().map(|s| s.to_string()));
            } else if k == "SPACE_SEPARATED" {
                space.extend(val.split_whitespace().map(|s| s.to_string()));
            }
        }
    }
    let mut vars: BTreeMap<String, Vec<String>> = BTreeMap::new();
    let mut plain: BTreeMap<String, String> = BTreeMap::new();
    for v in &files {
        for (k, val) in v {
            if k == "COLON_SEPARATED" || k == "SPACE_SEPARATED" {
                continue;
            }
            if colon.contains(k) || space.contains(k) {
                let sep = if colon.contains(k) { ':' } else { ' ' };
                let e = vars.entry(k.clone()).or_default();
                for part in val.split(sep).map(|s| s.trim()).filter(|s| !s.is_empty()) {
                    if !e.iter().any(|x| x == part) {
                        e.push(part.to_string());
                    }
                }
            } else {
                plain.insert(k.clone(), val.clone());
            }
        }
    }
    let ldpath = vars.remove("LDPATH").unwrap_or_default();
    let mut all: BTreeMap<String, String> = plain;
    for (k, v) in vars {
        let sep = if colon.contains(&k) { ":" } else { " " };
        all.insert(k, v.join(sep));
    }
    let mut prof = String::from(HEADER);
    let mut csh = String::from(HEADER.replace("/etc/profile", "/etc/csh.cshrc").replace("csh.cshrc.env", "csh.env"));
    for (k, v) in &all {
        prof.push_str(&format!("export {k}='{}'\n", v.replace('\'', "'\\''")));
        csh.push_str(&format!("setenv {k} '{}'\n", v.replace('\'', "'\\''")));
    }
    let mut changed = write_if_changed(&root.join("etc/profile.env"), &prof)?;
    write_if_changed(&root.join("etc/csh.env"), &csh)?;
    let mut ld = String::from("# ld.so.conf autogenerated by env-update; make all changes to\n# contents of /etc/env.d directory.\n");
    for p in &ldpath {
        ld.push_str(p);
        ld.push('\n');
    }
    changed |= write_if_changed(&root.join("etc/ld.so.conf"), &ld)?;
    if changed {
        info("Regenerated /etc/profile.env and /etc/ld.so.conf");
    }
    if run_ldconfig {
        let mut c = std::process::Command::new("ldconfig");
        if root != Path::new("/") {
            c.arg("-r").arg(root);
        }
        match c.env("PATH", crate::ebuild_env::PATH).status() {
            Ok(s) if s.success() => {}
            _ => warn("ldconfig failed"),
        }
    }
    Ok(())
}
